/** Prefix a site path with the language folder. English has no prefix. */
export function localePath(lang: Lang, path = '/'): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === 'en' ? clean : `/ms${clean === '/' ? '/' : clean}`;
}

export function formatDate(lang: Lang, d: Date): string {
  return d.toLocaleDateString(lang === 'ms' ? 'ms-MY' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
}
